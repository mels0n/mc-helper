"""Generate docs/reference/control-spool.md from the pydantic models.

Usage: python scripts/gen_reference.py --write | --check
"""

import json
import sys
from pathlib import Path
from typing import Any

from mc_helper.entities import TIMES, WEATHERS, Action, ActionResult, ControlRequest, ServerStatus
from mc_helper.entities.control import GAMERTAG_RE, MESSAGE_MAX
from mc_helper.entities.status import MAX_NAME_LENGTH, MAX_NAMES, MAX_VERSION_LENGTH
from mc_helper.shared.config import Settings

OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "reference" / "control-spool.md"


def _type(prop: dict[str, Any]) -> str:
    if "anyOf" in prop:
        return " or ".join(_type(option) for option in prop["anyOf"])
    if "$ref" in prop:
        return str(prop["$ref"]).rsplit("/", 1)[-1]
    kind = str(prop.get("type", "any"))
    if kind == "array":
        return f"array of {_type(prop.get('items', {}))}"
    if kind == "string" and "format" in prop:
        return f"string ({prop['format']})"
    return kind


def _constraints(prop: dict[str, Any]) -> str:
    keys = ("pattern", "maxLength", "minLength", "maxItems", "enum")
    return ", ".join(f"{key}: `{json.dumps(prop[key])}`" for key in keys if key in prop) or "none"


def _table(model: Any) -> list[str]:
    schema = model.model_json_schema()
    required = set(schema.get("required", []))
    lines = ["| Field | Type | Required | Constraints |", "| --- | --- | --- | --- |"]
    for name, prop in schema["properties"].items():
        lines.append(
            f"| `{name}` | {_type(prop)} | {'yes' if name in required else 'no'} "
            f"| {_constraints(prop)} |"
        )
    return lines


def render() -> str:
    max_age = Settings.model_fields["status_max_age_seconds"].default
    out = [
        "# Control spool",
        "",
        "Generated by `scripts/gen_reference.py` from the pydantic models in "
        "`src/mc_helper/entities/`. Do not edit by hand; run "
        "`uv run python scripts/gen_reference.py --write`. A test fails when this file is stale.",
        "",
        "The control folder holds `requests/`, `results/` and `status.json`.",
        "",
        "## Request: `requests/<id>.json` (written by this app)",
        "",
        *_table(ControlRequest),
        "",
        "Written to `requests/.tmp-<id>` first, then renamed to `requests/<id>.json`.",
        "",
        "### Actions and their `arg`",
        "",
        "| Action | `arg` |",
        "| --- | --- |",
    ]
    gamertag = f"gamertag, `{GAMERTAG_RE.pattern}`"
    rules = {
        Action.ALLOWLIST_ADD: gamertag,
        Action.ALLOWLIST_REMOVE: gamertag,
        Action.SET_SPAWN_HERE: f"{gamertag}, and currently online",
        Action.SET_TIME: " or ".join(f"`{t}`" for t in TIMES),
        Action.SET_WEATHER: " or ".join(f"`{w}`" for w in WEATHERS),
        Action.BACKUP_NOW: "`null`",
        Action.RESTART: "`null`",
    }
    out += [f"| `{action.value}` | {rules[action]} |" for action in Action]
    out += [
        "",
        "## Result: `results/<id>.json` (written by the supervisor)",
        "",
        *_table(ActionResult),
        "",
        f"`id` must equal the file name. Unknown fields are ignored. `message` is cut to "
        f"{MESSAGE_MAX} characters.",
        "",
        "## Status: `status.json` (written by the supervisor)",
        "",
        *_table(ServerStatus),
        "",
        f"Entries of `online` and `allowlist` that are not strings or are over "
        f"{MAX_NAME_LENGTH} characters are dropped, and each list is cut to {MAX_NAMES} "
        f"entries. `server_version` is cut to {MAX_VERSION_LENGTH} characters. A time without a "
        f"zone is read as UTC. The server counts as not answering when `updated` is more than "
        f"{max_age} seconds away from now (setting `STATUS_MAX_AGE_SECONDS`).",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render()
    if "--write" in argv:
        OUTPUT.write_text(text, encoding="utf-8", newline="\n")
        return 0
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        return 0 if current == text else 1
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
